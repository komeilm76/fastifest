/** JSON-compatible value accepted in developer-managed manifest fields. */
export type JsonValue =
  string | number | boolean | null | JsonValue[] | { [key: string]: JsonValue };

/** JSON object used for manifest extension members and nested records. */
export interface JsonObject {
  [key: string]: JsonValue;
}

/**
 * Developer-managed Web App Manifest members. Fastifest generates `icons` and
 * `screenshots`; those properties are rejected if supplied by a template.
 * Unknown extension members are preserved when their values are JSON-compatible.
 */
export interface ManifestTemplate {
  /** Stable URL identity for the installed application. */
  id?: string;
  /** Full application name. Provide this or `short_name`. */
  name?: string;
  /** Compact application name used where the full name does not fit. */
  short_name?: string;
  /** Human-readable application description. */
  description?: string;
  /** URL opened when the application launches. */
  start_url?: string;
  /** URL boundary describing which pages belong to the application. */
  scope?: string;
  /** Preferred display mode, such as `standalone` or `minimal-ui`. */
  display?: string;
  /** Ordered display-mode preferences used before falling back to `display`. */
  display_override?: string[];
  /** Preferred screen orientation. */
  orientation?: string;
  /** Application theme color, normally a CSS color string. */
  theme_color?: string;
  /** Background color shown while the application is loading. */
  background_color?: string;
  /** BCP 47 language tag for the application. */
  lang?: string;
  /** Primary text direction. */
  dir?: "ltr" | "rtl" | "auto";
  /** Categories that describe the application. */
  categories?: string[];
  /** Developer-authored application shortcuts. */
  shortcuts?: JsonObject[];
  /** Related platform applications. */
  related_applications?: JsonObject[];
  /** Whether the application prefers related platform applications. */
  prefer_related_applications?: boolean;
  /** Custom protocol handlers supported by the application. */
  protocol_handlers?: JsonObject[];
  /** Launch behavior configuration. */
  launch_handler?: JsonObject;
  /** Link-handling preference. */
  handle_links?: string;
  /** Additional URL scopes supported by the application. */
  scope_extensions?: JsonValue[];
  /** Generated by Fastifest; do not provide this in a template. */
  icons?: never;
  /** Generated by Fastifest; do not provide this in a template. */
  screenshots?: never;
  /** JSON-compatible manifest extension members. */
  [key: string]: JsonValue | undefined;
}

/** Optional, explicitly-authored metadata for one screenshot source basename. */
export interface ScreenshotMetadata {
  /** Human-readable screenshot caption included in the generated manifest. */
  label?: string;
  /** Screenshot form factor serialized as the manifest's `form_factor`. */
  formFactor?: "narrow" | "wide";
}

/**
 * User-facing configuration. Input and template paths are relative to the
 * project root; generated output subdirectories are relative to `paths.public`.
 * Only the documented keys are accepted by `validateConfig`.
 */
export interface FastifestConfig {
  /** Filesystem locations for project inputs and generated outputs. */
  paths?: {
    /** Public directory; defaults to `./public`, relative to the project root. */
    public?: string;
    /** Manifest location; must resolve to `manifest.json` directly inside `public`. */
    manifest?: string;
    /** Non-recursive logo input directory; defaults to `./assets/logos`. */
    logos?: string;
    /** Optional non-recursive screenshot input directory; defaults to `./assets/screenshots`. */
    screenshots?: string;
    /** Generated output directories, relative to the public root. */
    output?: {
      /** Generated icon directory; defaults to `./icons`. */
      logos?: string;
      /** Generated screenshot directory; defaults to `./screenshots`. */
      screenshots?: string;
    };
  };
  /** Manifest template loading and first-run creation behavior. */
  template?: {
    /** TypeScript template path; defaults to `./manifest.template.ts`. */
    path?: string;
    /** Create a starter when missing; defaults to `true`. Existing files still load when false. */
    enabled?: boolean;
  };
  /** Controls replacement of Fastifest-reserved generated image files. */
  images?: {
    /** Replace existing managed image files; defaults to `true`. */
    overwrite?: boolean;
  };
  /** Optional metadata keyed by exact screenshot source basename. */
  screenshots?: {
    metadata?: Record<string, ScreenshotMetadata>;
  };
  /** Console logging configuration. */
  logging?: {
    /** Minimum emitted level; defaults to `info`. */
    level?: LogLevel;
  };
}

/**
 * Fully normalized internal configuration. Most callers should pass a
 * `FastifestConfig` to `resolveConfig` rather than constructing this directly.
 */
export interface ResolvedFastifestConfig {
  /** Canonical absolute consumer project directory. */
  projectRoot: string;
  /** Absolute public output root. */
  publicRoot: string;
  /** Absolute `manifest.json` path directly inside `publicRoot`. */
  manifestPath: string;
  /** Absolute logo input directory. */
  logosPath: string;
  /** Absolute optional screenshot input directory. */
  screenshotsPath: string;
  /** Absolute generated icon output directory. */
  iconsOutputPath: string;
  /** Absolute generated screenshot output directory. */
  screenshotsOutputPath: string;
  /** Absolute TypeScript template path. */
  templatePath: string;
  /** Whether a starter template should be created when missing. */
  templateEnabled: boolean;
  /** Whether reserved generated image outputs may be replaced. */
  overwrite: boolean;
  /** Screenshot annotations indexed by exact source basename. */
  screenshotMetadata: Record<string, ScreenshotMetadata>;
  /** Minimum emitted log level. */
  logLevel: LogLevel;
}

/** Available logger thresholds; `debug` is most verbose and `error` least verbose. */
export type LogLevel = "error" | "warn" | "info" | "debug";
