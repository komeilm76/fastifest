import { lstat, mkdir, open, readFile, unlink } from "node:fs/promises";
import { dirname, join, parse, resolve, sep } from "node:path";
import { createJiti } from "jiti";
import { FastifestError } from "../errors.js";
import { createLogger, type Logger } from "../logger.js";
import { ownOption } from "../own-property.js";
import type { JsonObject, JsonValue, ManifestTemplate } from "../types.js";

type UnknownRecord = Record<string, unknown>;
const STRING_FIELDS = [
  "id",
  "name",
  "short_name",
  "description",
  "start_url",
  "scope",
  "display",
  "orientation",
  "theme_color",
  "background_color",
  "lang",
  "handle_links",
];
const STRING_ARRAY_FIELDS = ["display_override", "categories"];
const OBJECT_ARRAY_FIELDS = [
  "shortcuts",
  "related_applications",
  "protocol_handlers",
];

function invalid(field: string, detail: string): never {
  throw new FastifestError(
    "TEMPLATE_INVALID",
    `Invalid manifest template${field ? `.${field}` : ""}: ${detail}`,
  );
}

function isRecord(value: unknown): value is UnknownRecord {
  if (typeof value !== "object" || value === null || Array.isArray(value))
    return false;
  const prototype = Object.getPrototypeOf(value);
  return prototype === Object.prototype || prototype === null;
}

function assertJsonValue(
  value: unknown,
  field: string,
  visited: WeakSet<object>,
): asserts value is JsonValue {
  if (value === null || typeof value === "string" || typeof value === "boolean")
    return;
  if (typeof value === "number") {
    if (!Number.isFinite(value)) invalid(field, "numbers must be finite.");
    return;
  }
  if (typeof value !== "object")
    invalid(field, "expected a JSON-compatible value.");
  if (visited.has(value)) invalid(field, "circular values are not supported.");
  visited.add(value);
  for (const key of Reflect.ownKeys(value)) {
    const descriptor = Object.getOwnPropertyDescriptor(value, key);
    if (descriptor && ("get" in descriptor || "set" in descriptor)) {
      invalid(field, "accessor properties are not JSON-compatible.");
    }
  }

  if (Array.isArray(value)) {
    for (let index = 0; index < value.length; index += 1) {
      if (!Object.hasOwn(value, index)) {
        invalid(`${field}[${index}]`, "sparse arrays are not JSON-compatible.");
      }
      assertJsonValue(value[index], `${field}[${index}]`, visited);
    }
  } else {
    if (!isRecord(value)) invalid(field, "objects must be plain JSON objects.");
    for (const [key, member] of Object.entries(value)) {
      assertJsonValue(member, field ? `${field}.${key}` : key, visited);
    }
  }
  visited.delete(value);
}

function requireString(value: unknown, field: string): asserts value is string {
  if (typeof value !== "string") invalid(field, "expected a string.");
}

function requireStringArray(
  value: unknown,
  field: string,
): asserts value is string[] {
  if (!Array.isArray(value)) invalid(field, "expected an array of strings.");
  for (let index = 0; index < value.length; index += 1) {
    if (!Object.hasOwn(value, index) || typeof value[index] !== "string") {
      invalid(field, "expected an array of strings.");
    }
  }
}

function requireObjectArray(
  value: unknown,
  field: string,
): asserts value is JsonObject[] {
  if (!Array.isArray(value))
    invalid(field, "expected an array of JSON objects.");
  for (let index = 0; index < value.length; index += 1) {
    if (!Object.hasOwn(value, index) || !isRecord(value[index])) {
      invalid(field, "expected an array of JSON objects.");
    }
  }
}

/**
 * Validate a manifest template's supported shape and JSON-compatible members.
 * At least one of `name` or `short_name` is required, and Fastifest-owned
 * `icons`/`screenshots` members may not be supplied. This validates the
 * template structure, not every Web App Manifest semantic constraint.
 *
 * @param value - Candidate default-exported template object.
 * @returns The validated manifest template.
 * @throws {FastifestError} With `TEMPLATE_INVALID` when validation fails.
 */
export function validateTemplate(value: unknown): ManifestTemplate {
  if (!isRecord(value)) invalid("", "expected a default-exported object.");
  assertJsonValue(value, "", new WeakSet<object>());
  const ownValue = Object.create(null) as UnknownRecord;
  for (const key of Reflect.ownKeys(value)) {
    const descriptor = Object.getOwnPropertyDescriptor(value, key);
    if (typeof key !== "string" || !descriptor?.enumerable) continue;
    Object.defineProperty(ownValue, key, {
      value: descriptor.value,
      configurable: true,
      enumerable: true,
      writable: true,
    });
  }
  if (Object.hasOwn(value, "icons"))
    invalid(
      "icons",
      "is generated by Fastifest and cannot be set in the template.",
    );
  if (Object.hasOwn(value, "screenshots")) {
    invalid(
      "screenshots",
      "is generated by Fastifest and cannot be set in the template.",
    );
  }
  for (const field of STRING_FIELDS) {
    if (ownValue[field] !== undefined) requireString(ownValue[field], field);
  }
  for (const field of ["name", "short_name"] as const) {
    if (
      typeof ownValue[field] === "string" &&
      ownValue[field].trim().length === 0
    ) {
      invalid(field, "expected a non-empty string.");
    }
  }
  if (
    typeof ownValue.name !== "string" &&
    typeof ownValue.short_name !== "string"
  ) {
    invalid("", "provide at least one of name or short_name.");
  }
  for (const field of STRING_ARRAY_FIELDS) {
    if (ownValue[field] !== undefined)
      requireStringArray(ownValue[field], field);
  }
  if (
    ownValue.dir !== undefined &&
    ownValue.dir !== "ltr" &&
    ownValue.dir !== "rtl" &&
    ownValue.dir !== "auto"
  ) {
    invalid("dir", 'expected "ltr", "rtl", or "auto".');
  }
  if (
    ownValue.prefer_related_applications !== undefined &&
    typeof ownValue.prefer_related_applications !== "boolean"
  ) {
    invalid("prefer_related_applications", "expected a boolean.");
  }
  if (
    ownValue.launch_handler !== undefined &&
    !isRecord(ownValue.launch_handler)
  ) {
    invalid("launch_handler", "expected a JSON object.");
  }
  if (
    ownValue.scope_extensions !== undefined &&
    !Array.isArray(ownValue.scope_extensions)
  ) {
    invalid("scope_extensions", "expected an array.");
  }
  for (const field of OBJECT_ARRAY_FIELDS) {
    if (ownValue[field] !== undefined)
      requireObjectArray(ownValue[field], field);
  }

  return ownValue as ManifestTemplate;
}

/**
 * Load a trusted TypeScript manifest template and validate its default export.
 * The template is executable code; load only files you trust.
 *
 * @param templatePath - Path to the TypeScript template; an absolute path gives unambiguous resolution.
 * @returns The validated `ManifestTemplate` value.
 * @throws {FastifestError} With `TEMPLATE_LOAD_FAILED` for loading/evaluation
 * errors or `TEMPLATE_INVALID` for invalid template values.
 */
export async function loadTemplate(
  templatePath: string,
): Promise<ManifestTemplate> {
  try {
    const jiti = createJiti(import.meta.url, {
      interopDefault: true,
      moduleCache: false,
    });
    const value = await jiti.import<unknown>(templatePath, { default: true });
    return validateTemplate(value);
  } catch (error) {
    if (error instanceof FastifestError) throw error;
    throw new FastifestError(
      "TEMPLATE_LOAD_FAILED",
      `Could not load manifest template ${templatePath}.`,
      error,
    );
  }
}

const STARTER_TEMPLATE = `/**
 * Customize these values for your application. Fastifest creates this file
 * once and will not overwrite it. The first run stops after creating it.
 */
export default {
  name: "My Web App",
  short_name: "My App",
  start_url: "/",
  display: "standalone",
};
`;

/** Options for create-only starter behavior and template-load logging. */
export interface LoadOrCreateTemplateOptions {
  /** Controls creation only; an existing template is always loaded. Defaults to `true`. */
  enabled?: boolean;
  /** Optional logger; defaults to an `info` logger. */
  logger?: Logger;
}

/**
 * Result of loading or creating a template. Treat `status: "created"` as a
 * first-run stop signal; the starter must be customized before generation.
 */
export type LoadOrCreateTemplateResult =
  | {
      /** Existing template loaded and validated. */
      status: "loaded";
      /** Validated existing template. */
      template: ManifestTemplate;
    }
  | {
      /** Starter created; no template data should be used for generation yet. */
      status: "created";
      /** Absolute path of the starter file. */
      templatePath: string;
      /** Human-readable instruction to customize the starter and run again. */
      guidance: string;
    };

function errorCode(error: unknown): string | undefined {
  if (typeof error === "object" && error !== null && "code" in error) {
    return typeof error.code === "string" ? error.code : undefined;
  }
  return undefined;
}

async function inspectTemplatePath(
  templatePath: string,
  expected: "file" | "directory" = "file",
): Promise<boolean> {
  const absolute = resolve(templatePath);
  const parsed = parse(absolute);
  const segments = absolute
    .slice(parsed.root.length)
    .split(sep)
    .filter(Boolean);
  let current = parsed.root;

  for (const [index, segment] of segments.entries()) {
    current = join(current, segment);
    let info;
    try {
      info = await lstat(current);
    } catch (error) {
      if (errorCode(error) === "ENOENT") return false;
      throw new FastifestError(
        "IO_FAILED",
        `Could not inspect manifest template path: ${current}`,
        error,
      );
    }
    if (info.isSymbolicLink()) {
      throw new FastifestError(
        "UNSAFE_PATH",
        `Manifest template path contains a symlink or reparse point: ${current}`,
      );
    }
    if (index < segments.length - 1 && !info.isDirectory()) {
      throw new FastifestError(
        "PATH_INVALID",
        `Manifest template parent is not a directory: ${current}`,
      );
    }
    if (
      index === segments.length - 1 &&
      !(expected === "file" ? info.isFile() : info.isDirectory())
    ) {
      throw new FastifestError(
        "PATH_INVALID",
        expected === "file"
          ? `Manifest template path is not a regular file: ${current}`
          : `Manifest template parent is not a directory: ${current}`,
      );
    }
  }
  if (segments.length === 0) {
    const rootInfo = await lstat(parsed.root);
    if (rootInfo.isSymbolicLink()) {
      throw new FastifestError(
        "UNSAFE_PATH",
        `Manifest template path contains a symlink or reparse point: ${parsed.root}`,
      );
    }
    const rootMatches =
      expected === "file" ? rootInfo.isFile() : rootInfo.isDirectory();
    if (!rootMatches) {
      throw new FastifestError(
        "PATH_INVALID",
        expected === "file"
          ? `Manifest template path is not a regular file: ${parsed.root}`
          : `Manifest template parent is not a directory: ${parsed.root}`,
      );
    }
  }
  return true;
}

async function createStarterTemplate(templatePath: string): Promise<boolean> {
  const parent = dirname(templatePath);
  await inspectTemplatePath(parent, "directory");
  try {
    await mkdir(parent, { recursive: true });
  } catch (error) {
    throw new FastifestError(
      "IO_FAILED",
      `Could not create manifest template directory: ${parent}`,
      error,
    );
  }

  if (!(await inspectTemplatePath(parent, "directory"))) {
    throw new FastifestError(
      "PATH_INVALID",
      `Manifest template parent directory does not exist: ${parent}`,
    );
  }

  let handle;
  try {
    handle = await open(templatePath, "wx", 0o666);
  } catch (error) {
    if (errorCode(error) === "EEXIST") return false;
    throw new FastifestError(
      "IO_FAILED",
      `Could not create manifest template: ${templatePath}`,
      error,
    );
  }

  let ownedInfo;
  try {
    ownedInfo = await handle.stat();
    await handle.writeFile(STARTER_TEMPLATE, "utf8");
    await handle.sync();
  } catch (error) {
    try {
      await handle.close();
    } catch {
      // Preserve the original write error.
    }
    if (ownedInfo) {
      try {
        const current = await lstat(templatePath);
        if (
          current.isFile() &&
          !current.isSymbolicLink() &&
          current.dev === ownedInfo.dev &&
          current.ino === ownedInfo.ino
        ) {
          await unlink(templatePath);
        }
      } catch {
        // Preserve the original write error; cleanup is best-effort.
      }
    }
    throw new FastifestError(
      "IO_FAILED",
      `Could not write manifest template: ${templatePath}`,
      error,
    );
  }

  try {
    await handle.close();
  } catch (error) {
    throw new FastifestError(
      "IO_FAILED",
      `Could not close manifest template: ${templatePath}`,
      error,
    );
  }

  if (!(await inspectTemplatePath(templatePath))) {
    throw new FastifestError(
      "IO_FAILED",
      `Manifest template disappeared during creation: ${templatePath}`,
    );
  }
  const installed = await lstat(templatePath);
  if (
    installed.isSymbolicLink() ||
    !installed.isFile() ||
    installed.dev !== ownedInfo.dev ||
    installed.ino !== ownedInfo.ino
  ) {
    throw new FastifestError(
      "UNSAFE_PATH",
      `Manifest template changed unexpectedly during creation: ${templatePath}`,
    );
  }
  return true;
}

/**
 * Load an existing template or create a starter and signal the caller to stop.
 * Existing templates are loaded regardless of `options.enabled`. If the file is
 * missing, creation defaults to enabled; with creation disabled this rejects
 * using `TEMPLATE_MISSING`.
 *
 * @param templatePath - Absolute or relative template path; relative paths resolve from the current working directory.
 * @param options - Creation behavior and optional logger.
 * @returns A loaded template or a `created` stop result with next-step guidance.
 * @throws {FastifestError} With template, path-safety, or I/O error codes.
 */
export async function loadOrCreateTemplate(
  templatePath: string,
  options: LoadOrCreateTemplateOptions = {},
): Promise<LoadOrCreateTemplateResult> {
  const absoluteTemplatePath = resolve(templatePath);
  const logger = ownOption(options, "logger") ?? createLogger();
  const enabled = ownOption(options, "enabled") ?? true;

  if (await inspectTemplatePath(absoluteTemplatePath)) {
    return {
      status: "loaded",
      template: await loadTemplate(absoluteTemplatePath),
    };
  }

  if (!enabled) {
    throw new FastifestError(
      "TEMPLATE_MISSING",
      `Manifest template not found: ${absoluteTemplatePath}. Create the file or set template.enabled to true to generate a starter.`,
    );
  }

  const created = await createStarterTemplate(absoluteTemplatePath);
  if (!created) {
    if (!(await inspectTemplatePath(absoluteTemplatePath))) {
      throw new FastifestError(
        "IO_FAILED",
        `Manifest template disappeared during creation: ${absoluteTemplatePath}`,
      );
    }
    let existingContents: string;
    try {
      existingContents = await readFile(absoluteTemplatePath, "utf8");
    } catch (error) {
      throw new FastifestError(
        "IO_FAILED",
        `Could not read manifest template after a create-only collision: ${absoluteTemplatePath}`,
        error,
      );
    }
    if (existingContents !== STARTER_TEMPLATE) {
      return {
        status: "loaded",
        template: await loadTemplate(absoluteTemplatePath),
      };
    }
  }

  const guidance = `Created manifest template at ${absoluteTemplatePath}. Customize it, then run Fastifest again. No manifest was generated.`;
  logger.info(guidance);
  return { status: "created", templatePath: absoluteTemplatePath, guidance };
}
